test('seller entry, real clipboard, status details, hash navigation and clipboard fallback', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('button', { name: 'Seller', exact: true }).click()
  await expect(page).toHaveURL(/\/seller$/)
  await page.getByRole('button', { name: 'Copy demo link' }).first().click()
  await expect(page.getByRole('status')).toHaveText('Demo listing link copied.')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('http://127.0.0.1:5173/buyer/skills/invoice-field-extractor')
  await page.getByRole('link', { name: 'Evaluation activity', exact: true }).click()
  await expect(page.locator('#activity')).toBeFocused()
  await page.getByRole('button', { name: 'View AG-003 status' }).click()
  await expect(page.getByRole('dialog')).toContainText('Capture pending · not confirmed')
  await expect(page.getByRole('dialog')).toContainText('Locked')
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'View AG-002 status' }).click()
  await expect(page.getByRole('dialog')).toContainText('COMPLETED · simulated capture')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'View AG-001 status' }).click()
  await expect(page.getByRole('dialog')).toContainText('Not captured · authorization voided')
  await page.keyboard.press('Escape')
  await page.evaluate(() => Object.defineProperty(navigator.clipboard, 'writeText', { value: () => Promise.reject(new Error('Denied')), configurable: true }))
  await page.getByRole('button', { name: 'Copy demo link' }).last().click()
  await expect(page.getByLabel('Demo listing URL')).toHaveValue('http://127.0.0.1:5173/buyer/skills/invoice-field-extractor')
  await page.keyboard.press('Escape')
  await page.goto('/?panel=seller')
  await expect(page).toHaveURL(/\/seller$/)
  await page.getByRole('link', { name: 'View listing', exact: true }).click()
  await expect(page).toHaveURL(/\/buyer\/skills\/invoice-field-extractor$/)
})

test('draft registration returns a fixed custom package with no misleading checkout', async ({ page }) => {
  await page.goto('/seller')
  await page.getByRole('link', { name: 'Continue editing' }).click()
  await page.getByLabel('Price', { exact: true }).fill('19.95')
  await page.getByRole('link', { name: 'Back to my listings' }).click()
  await page.getByRole('link', { name: 'Register a skill' }).click()
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Invoice field extractor')
  await page.getByRole('link', { name: 'Back to my listings' }).click()
  await page.getByRole('link', { name: 'Continue editing' }).click()
  await expect(page.getByLabel('Price', { exact: true })).toHaveValue('19.95')
  await page.getByRole('button', { name: 'Register this version' }).click()
  const hash = await page.locator('.seller-hash').textContent()
  await page.getByRole('link', { name: 'View my listings' }).click()
  await expect(page.locator('#listings')).toBeFocused()
  const row = page.getByRole('row').filter({ hasText: 'Product attribute mapper' }).filter({ hasText: 'USD 19.95' })
  await expect(row).toContainText('Registered locally')
  await expect(row.getByRole('link')).toHaveCount(0)
  await row.getByRole('button', { name: 'View local package' }).click()
  await expect(page.locator('.seller-hash')).toHaveText(hash!)
  await page.getByText('View fixed instructions and public example', { exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Blue cotton shirt, size M.')
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.reload()
  await expect(page.getByRole('link', { name: 'Continue editing' })).toBeVisible()
  await expect(page.getByText('USD 19.95')).toHaveCount(0)
})

