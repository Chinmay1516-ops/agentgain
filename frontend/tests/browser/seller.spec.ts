import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir } from 'node:fs/promises'

test('registration validates the offer, freezes the local package and supports draft entry', async ({ page }) => {
  await page.goto('/seller/register')
  await page.getByLabel('Price', { exact: true }).fill('-1')
  await page.getByRole('button', { name: 'Register this version' }).click()
  await expect(page.getByRole('alert')).toContainText('highlighted')
  await expect(page.getByLabel('Price', { exact: true })).toBeFocused()
  await page.getByLabel('Price', { exact: true }).fill('19.95')
  await page.getByRole('button', { name: 'Register this version' }).click()
  await expect(page.getByRole('alert')).toContainText('new version')
  await page.getByLabel('Version', { exact: true }).fill('v1.1')
  await page.getByRole('button', { name: 'Register this version' }).click()
  await expect(page.getByRole('dialog')).toContainText('Nothing has been published')
  await expect(page.locator('.seller-hash')).toHaveText(/^[a-f0-9]{64}$/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Registered locally' })).toBeDisabled()
  await page.goto('/seller/register?draft=attributes-draft')
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Product attribute mapper')
  await expect(page.getByLabel('Price', { exact: true })).toHaveValue('')
  await page.goto('/seller/register?draft=unknown')
  await expect(page.getByRole('heading', { name: 'Draft not available.' })).toBeVisible()
  await page.goto('/seller/register?draft=constructor')
  await expect(page.getByRole('heading', { name: 'Draft not available.' })).toBeVisible()
})

